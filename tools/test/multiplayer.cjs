// Teste do multiplayer: sobe o servidor, abre 2 navegadores independentes, cria 2 contas e 2 heróis
// e confere: presença (um vê o outro), chat, salvamento na nuvem (sobrevive a recarregar) e ranking.
// Uso: node tools/test/multiplayer.cjs   (precisa de: cd server && npm install)
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs'), os = require('os'), path = require('path');
const ROOT = path.resolve(__dirname, '../..'), OUT = path.join(ROOT, 'build/test');
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'valdaria-'));
  const port = 18000 + Math.floor(Math.random() * 1000);
  const srv = spawn('node', [path.join(ROOT, 'server/server.js')], { env: { ...process.env, PORT: port, DATA_DIR: data, GW_FORCE: '1' }, stdio: 'pipe' });
  await new Promise((r) => srv.stdout.on('data', (d) => { if (/rodando/.test(d)) r(); }));
  const url = `http://localhost:${port}/`;
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const out = [], errs = [], ok = (n, c, i = '') => out.push(`${c ? '✅' : '❌'} ${n}${i ? ' — ' + i : ''}`);
  const player = async (user, cls, hero) => {
    const ctx = await b.newContext({ viewport: { width: 1100, height: 700 } });
    const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(user + ': ' + e.message));
    await p.goto(url); await p.waitForSelector('#acct-user', { timeout: 10000 });
    await p.fill('#acct-user', user); await p.fill('#acct-pass', 'segredo123'); await p.click('[data-act="acct-register"]');
    await p.waitForSelector('.acct-on', { timeout: 10000 });
    await p.click('[data-new="0"]'); await p.click(`[data-faction="${cls === 'paladino' ? 'luz' : 'ferro'}"]`); await p.click(`[data-cls="${cls}"]`);
    await p.fill('#char-name', hero); await p.click('#create-btn');
    await p.waitForTimeout(500); await p.evaluate(() => { S.tut = 99; renderTut(); });
    return p;
  };
  const until = async (P, fn, arg, ms = 5000) => { for (let t = 0; t < ms; t += 250) { if (await P.evaluate(fn, arg)) return true; await P.waitForTimeout(250); } return false; };
  const A = await player('Alfa', 'gladiador', 'Brutus');
  const B = await player('Beta', 'paladino', 'Lumen');
  await A.waitForTimeout(6000);
  const seeA = await A.evaluate(() => [...Net.st.others.values()].map((o) => o.name).join(','));
  const seeB = await B.evaluate(() => [...Net.st.others.values()].map((o) => o.name).join(','));
  ok('Presença: cada um vê o outro no mapa', seeA.includes('Lumen') && seeB.includes('Brutus'), `Alfa vê [${seeA}], Beta vê [${seeB}]`);
  for (const P of [A, B]) await P.evaluate(() => { $('#modal').classList.add('hidden'); S.settings.auto = false; R.mon = null; R.move = null; });
  const pa = await A.evaluate(() => ({ x: R.pos.x, z: R.pos.z }));
  await B.evaluate((pa) => { R.pos.x = pa.x + 1.6; R.pos.z = pa.z + 0.4; }, pa);
  await A.waitForTimeout(2500);
  const drawn = await A.evaluate(() => document.querySelectorAll('#pl-labels .pl-label').length);
  ok('Outro jogador desenhado com nome', drawn >= 1);
  await A.screenshot({ path: path.join(OUT, 'multiplayer.png') });
  await A.evaluate(() => chatCommand('Olá do Brutus!'));
  const got = await until(B, () => R.log.some((l) => l.msg.includes('Olá do Brutus!')));
  ok('Chat chega no outro jogador', got);
  // grupo
  await B.evaluate(() => { window._inv = null; const o = Net.onSocial; Net.onSocial = (m) => { if (m.t === 'pinvite' || m.t === 'ginvite') window._inv = m; else o(m); }; });
  await A.evaluate(() => chatCommand('/convidar Lumen'));
  await until(B, () => !!window._inv);
  const inv = await B.evaluate(() => window._inv && window._inv.from);
  ok('Convite de grupo chega', inv === 'Brutus', inv);
  await B.evaluate(() => Net.soc('paccept', { fid: window._inv.fid }));
  await until(A, () => Net.st.party && Net.st.party.members.length === 2);
  const pa2 = await A.evaluate(() => Net.st.party && Net.st.party.members.map((m) => m.name).join(','));
  ok('Grupo formado', !!pa2 && pa2.includes('Lumen') && pa2.includes('Brutus'), pa2);
  ok('Bônus de XP do grupo no mesmo mapa', await until(A, () => socialXp() > 1.05 && !!document.getElementById('party-hud')));
  const xpB0 = await B.evaluate(() => S.xp + S.lvl * 1e9);
  await A.evaluate(() => { const m = makeMonster('Lobo Filhote', '🐺', 3, false, 2); Object.assign(m, { x: 0, z: 0, home: { x: 0, z: 0 } }); R.mons.push(m); killMonster(m); });
  let shared = false; for (let i = 0; i < 12 && !shared; i++) { await B.waitForTimeout(500); shared = await B.evaluate((x0) => S.xp + S.lvl * 1e9 > x0, xpB0); }
  ok('XP dividido com o grupo', shared);
  await B.evaluate(() => { window._chats = []; const oc = Net.onChat; Net.onChat = (m) => { window._chats.push(m); oc(m); }; });
  await A.evaluate(() => chatCommand('/p só o grupo vê'));
  ok('Chat do grupo', await until(B, () => window._chats.some((m) => m.ch === 'party' && m.text.includes('só o grupo vê')), null, 6000));
  // guilda
  await A.evaluate(() => { S.lvl = 25; S.gold = 60000; netState(); });
  await A.waitForTimeout(400);
  await A.evaluate(() => { stopLoop(); window._g0 = S.gold; R.win = null; openWin('social'); $('#guild-name').value = 'Lobos de Ferro'; socialAction('gcreate'); });
  await A.waitForTimeout(800);
  const g1 = await A.evaluate(() => Net.st.guild && Net.st.guild.name + ':' + (window._g0 - S.gold));
  await A.evaluate(() => startLoop());
  ok('Fundar guilda (cobra ouro)', g1 === 'Lobos de Ferro:50000', g1);
  await A.evaluate(() => chatCommand('/convidarguilda Lumen'));
  await until(B, () => !!(window._inv && window._inv.guild));
  const ginv = await B.evaluate(() => window._inv && window._inv.guild);
  await B.evaluate(() => Net.soc('gaccept'));
  await until(A, () => Net.st.guild && Net.st.guild.members.length === 2 && Net.st.guild.members.every((m) => m.online));
  const gm = await A.evaluate(() => Net.st.guild.members.map((m) => m.name + (m.online ? '+' : '')).join(','));
  ok('Convidar e entrar na guilda', ginv === 'Lobos de Ferro' && gm.includes('Lumen+') && gm.includes('Brutus+'), gm);
  await B.evaluate(() => chatCommand('/g olá guilda'));
  ok('Chat da guilda', await until(A, () => R.log.some((l) => l.msg.includes('olá guilda') && l.msg.includes('[guilda]'))));
  await A.screenshot({ path: path.join(OUT, 'social.png') });
  const rk = await A.evaluate(async () => (await Net.ranking()).find((r) => r.name === 'Lumen'));
  ok('Guilda aparece no ranking', !!rk && rk.guild === 'Lobos de Ferro');
  await A.evaluate(() => { const k = Net.st.guild.members.find((m) => m.name === 'Lumen').key; Net.soc('gkick', { user: k }); });
  ok('Líder expulsa membro', await until(B, () => Net.st.guild === null));
  // masmorra em grupo (Alfa é o líder do grupo)
  await B.evaluate(() => { const o = Net.onSocial; Net.onSocial = (m) => { if (m.t === 'coop' && m.k === 'start') window._coop = m; else if (m.t === 'tinvite') window._tinv = m; else o(m); }; });
  await A.evaluate(() => { S.lvl = 30; S.dunCd = {}; S.gold += 1e6; setTown(false); });
  await B.evaluate(() => { S.lvl = 30; S.hp = derived().maxHp; setTown(false); });
  await A.waitForTimeout(500);
  ok('Botão de masmorra em grupo para o líder', await A.evaluate(() => canCoop() && tabMaps().includes('data-codun')));
  await A.evaluate(() => { S.settings.auto = false; startCoop('z2'); for (const m of R.mons) { m.atk = 0; m.aggro = false; } });
  ok('Convite da masmorra chega ao colega', await until(B, () => !!window._coop));
  await B.evaluate(() => { joinCoop(window._coop.d.zone, window._coop.from); S.settings.auto = false; });
  ok('Colega vê os mesmos monstros do líder', await until(B, () => R.dungeon && R.dungeon.coop && R.mons.length > 0 && R.mons.every((m) => m.sid))
    && await A.evaluate((sid) => aliveMons().some((m) => m.sid === sid), await B.evaluate(() => R.mons[0].sid)));
  const xpB1 = await B.evaluate(() => S.xp + S.lvl * 1e9);
  const sid0 = await B.evaluate(() => { const m = aliveMons()[0]; if (!m) return 'nenhum:' + R.mons.length + ':' + !!R.dungeon; hitMonster(m, 9999, null, derived()); if (m.hp <= 0) killMonster(m); return m.sid; });
  ok('Golpe do colega tira vida no líder', await until(A, (sid) => !aliveMons().some((m) => m.sid === sid), sid0), sid0);
  ok('Colega ganha o XP do abate', await until(B, (x0) => S.xp + S.lvl * 1e9 > x0, xpB1));
  ok('Os dois se veem dentro da masmorra', await until(A, () => [...Net.st.others.values()].some((o) => o.name === 'Lumen'), null, 6000));
  await A.evaluate(() => { for (let f = 0; f < 3; f++) { for (const m of aliveMons()) { m.hp = 0; killMonster(m); } for (let i = 0; i < 30; i++) tick(); } });
  ok('Fim da masmorra leva o colega junto (com prêmio)', await until(B, () => !R.dungeon && (S.stats.dungeons || 0) >= 1, null, 6000));
  // troca
  await B.evaluate(() => { S.inv = []; const it = genItem(30, 3, 'arma'); it.uid = 'lumen-item'; it.name = 'Lâmina de Teste da Troca'; window._itName = it.name; S.inv.push(it); S.gold = 5000; });
  await A.evaluate(() => { S.inv = S.inv.slice(0, 5); S.gold = 100000; });
  await A.evaluate(() => chatCommand('/trocar Lumen'));
  ok('Pedido de troca chega', await until(B, () => !!window._tinv));
  await B.evaluate(() => Net.soc('taccept', { fid: window._tinv.fid }));
  ok('Janela de troca abre nos dois', await until(A, () => R.win === 'troca' && !!Net.st.trade) && await until(B, () => R.win === 'troca'));
  await B.evaluate(() => { R.tradeSel.add('lumen-item'); tradeSend(); });
  await A.evaluate(() => { R.tradeGold = 30000; tradeSend(); });
  await A.waitForTimeout(600);
  await A.evaluate(() => renderTab()); await A.screenshot({ path: path.join(OUT, 'troca.png') });
  for (const P of [A, B]) await P.evaluate(() => tradeAction('lock'));
  await until(A, () => Net.st.trade && Net.st.trade.lockMe && Net.st.trade.lockThem);
  for (const P of [A, B]) await P.evaluate(() => tradeAction('confirm'));
  const gotItem = await until(A, () => S.inv.some((i) => i.name && R.win !== 'troca') && (S.stats.trades || 0) === 1);
  const sides = await A.evaluate(() => S.gold) + ' / ' + await B.evaluate(() => S.gold + ' itens ' + S.inv.length);
  const itName = await B.evaluate(() => window._itName);
  ok('Troca concluída: item por ouro', gotItem && (await A.evaluate((n) => S.inv.some((i) => i.name === n), itName)) && (await B.evaluate(() => S.gold >= 35000 && !S.inv.some((i) => i.uid === 'lumen-item'))), sides);
  await B.evaluate(() => Net.soc('pleave'));
  ok('Sair do grupo desfaz grupo de 2', await until(A, () => Net.st.party === null));
  // PK
  for (const P of [A, B]) await P.evaluate(() => { S.lvl = 50; S.settings.pk = true; S.settings.auto = false; S.zone = 'z8'; R.worldZone = null; if (R.inTown) setTown(false); R.dead = 0; S.hp = derived().maxHp; });
  await A.waitForTimeout(600);
  await A.evaluate(() => { R.mons = []; R.pos = { x: 0, z: 0 }; }); await B.evaluate(() => { R.mons = []; R.pos = { x: 1.5, z: 0 }; S.pots = {}; S.settings.autoHp = 0; });
  ok('Os dois aparecem com PK no mapa de PK', await until(A, () => [...Net.st.others.values()].some((o) => o.name === 'Lumen' && o.pk)));
  const bid = await A.evaluate(() => [...Net.st.others.entries()].find(([, o]) => o.name === 'Lumen')[0]);
  const xpB2 = await B.evaluate(() => S.xp + S.lvl * 1e9);
  await A.evaluate((id) => { window.gameOrder({ type: 'pvp', id }); }, bid);
  ok('Golpe de PK tira vida do outro', await until(B, () => S.hp < derived().maxHp, null, 6000));
  await B.evaluate(() => { S.hp = 5; });
  ok('Derrota no PK sem perder XP', await until(B, (x0) => R.dead > 0 && S.stats.pvpDeaths === 1 && S.xp + S.lvl * 1e9 >= x0, xpB2, 8000));
  ok('Vencedor ganha Honra', await until(A, () => (S.stats.pvpKills || 0) === 1, null, 5000) && (await A.evaluate(async () => (await Net.ranking()).find((r) => r.name === 'Brutus').honor)) === 1);
  await B.evaluate(() => { R.dead = 0; S.hp = derived().maxHp; R.pvpProt = 0; S.settings.pk = false; });
  await A.waitForTimeout(700);
  const why = await A.evaluate((id) => pkWhyNot(Net.st.others.get(id)), bid);
  ok('Quem desliga o PK não pode ser atacado', why.includes('desligado'), why);
  await A.evaluate(() => { S.settings.pk = true; S.zone = 'z2'; R.worldZone = null; });
  ok('Fora dos mapas de PK ninguém ataca', await A.evaluate(() => pkWhyNot({ name: 'X', pk: true, lvl: 60 }).includes('não é mapa de PK')));
  // Cerco da Coroa (o servidor de teste deixa aberto)
  await B.evaluate(() => { S.gold = 100000; R.win = null; openWin('social'); $('#guild-name').value = 'Clã Beta'; socialAction('gcreate'); });
  ok('Segundo clã fundado', await until(B, () => Net.st.guild && Net.st.guild.name === 'Clã Beta'));
  ok('Cerco aberto aparece para os dois', await until(A, () => gwOpen(), null, 7000) && await until(B, () => gwOpen(), null, 7000));
  for (const P of [A, B]) await P.evaluate(() => { S.settings.pk = false; R.dead = 0; S.hp = derived().maxHp; R.pvpProt = 0; enterGW(); });
  ok('Os dois entram na Fortaleza', (await A.evaluate(() => S.zone)) === 'gw' && (await B.evaluate(() => S.zone)) === 'gw');
  await A.waitForTimeout(1800); // o servidor precisa saber que entraram (o estado vai 5x por segundo)
  const gwDbg = await A.evaluate(() => { R.mons = []; R.pos = { x: 0, z: 0 }; let c; for (let i = 0; i < 200 && !c; i++) { const m = spawnWorldMonster(); if (m && m.crystal) c = m; } if (!c) return 'sem cristal: zona ' + S.zone + ' mons ' + R.mons.length; c.hp = 0; killMonster(c); return 'ok'; });
  if (gwDbg !== 'ok') ok('Cristal na Fortaleza', false, gwDbg);
  await B.evaluate(() => { R.mons = []; R.pos = { x: 1.5, z: 0 }; });
  ok('Cristal dá 50 pontos ao clã', await until(A, () => wk() && wk().board.some((b) => b.name === 'Lobos de Ferro' && b.pts >= 50), null, 14000));
  ok('No Cerco clãs diferentes lutam sem Modo PK', await until(A, () => { const o = [...Net.st.others.values()].find((x) => x.name === 'Lumen'); return !!o && o.g === 'Clã Beta' && pkWhyNot(o) === ''; }, null, 6000));
  // Arena da Sobrevivência em grupo
  await B.evaluate(() => { window._inv = null; window._coop = null; });
  await A.evaluate(() => { S.zone = 'z5'; R.worldZone = null; chatCommand('/convidar Lumen'); });
  await B.evaluate(() => { S.zone = 'z5'; R.worldZone = null; });
  await until(B, () => !!window._inv); await B.evaluate(() => Net.soc('paccept', { fid: window._inv.fid }));
  await until(A, () => Net.st.party && Net.st.party.members.length === 2);
  await A.evaluate(() => { S.arenaWk = null; S.settings.auto = false; enterArena(true); for (const m of R.mons) m.atk = 0; });
  ok('Convite da Arena chega ao colega', await until(B, () => !!window._coop && window._coop.d.arena));
  await B.evaluate(() => { S.arenaWk = null; joinCoop(window._coop.d.zone, window._coop.from); R.dungeon.arena = true; R.dungeon.floors = Infinity; });
  await A.evaluate(() => { for (let r = 0; r < 3; r++) { for (const m of aliveMons()) { m.hp = 0; killMonster(m); } for (let i = 0; i < 30; i++) tick(); } R.dungeon.t = 0.05; tick(); tick(); });
  ok('Recorde da Arena em grupo vai para o ranking da semana', await until(A, () => wk() && wk().sodBest && wk().sodBest.rounds === 3, null, 8000));
  const colega = await until(B, () => !R.dungeon && (S.arenaWk && S.arenaWk.best === 3), null, 10000);
  ok('Colega sai junto com o resultado', colega, colega ? '' : await B.evaluate(() => JSON.stringify({ dun: R.dungeon && { arena: R.dungeon.arena, floor: R.dungeon.floor, cleared: R.dungeon.cleared }, coop: R.coop && { lead: R.coop.lead }, wk: S.arenaWk, log: R.log.slice(-25).map((l) => l.msg.slice(0, 60)) })));
  await B.evaluate(() => { S.gold = 777; save(); Net.flush(); });
  await B.waitForTimeout(800);
  await B.reload(); await B.waitForSelector('.acct-on', { timeout: 10000 });
  const cloud = await B.evaluate(() => { const c = loadSlot(0); return c && c.name + ':' + c.gold; });
  ok('Salvamento na nuvem sobrevive a recarregar', cloud === 'Lumen:777', cloud);
  const rank = await A.evaluate(async () => (await Net.ranking()).map((r) => r.name).join(','));
  ok('Ranking', rank.includes('Brutus') && rank.includes('Lumen'), rank);
  const bad = await A.evaluate(async () => { const r = await fetch('api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ user: 'Alfa', pass: 'errada' }) }); return r.status; });
  ok('Senha errada é recusada', bad === 401);
  const leak = await A.evaluate(async () => (await fetch('server/data/db.json')).status);
  ok('Banco de dados não fica público', leak === 404);
  await b.close(); srv.kill();
  console.log(out.join('\n'));
  if (errs.length) console.log('❌ Erros:\n' + errs.join('\n'));
  process.exit(out.some((l) => l.startsWith('❌')) || errs.length ? 1 : 0);
})();
